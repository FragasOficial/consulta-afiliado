function filtrarFiliados() {
  const input = document.getElementById("filtro-nome").value.toLowerCase();
  const resultado = document.getElementById("resultado");
  resultado.innerHTML = "";

  const filtrados = filiados.filter(f =>
    f.nome.toLowerCase().includes(input) || f.id.includes(input)
  );

  if (filtrados.length === 0) {
    resultado.innerHTML = "<li>Nenhum resultado encontrado.</li>";
  } else {
    filtrados.forEach(f => {
      const li = document.createElement("li");
      li.textContent = `${f.id} - ${f.nome}`;
      resultado.appendChild(li);
    });
  }
}